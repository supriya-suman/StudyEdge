/* ---------- full written lessons (other terms are generated by the AI Mentor) ---------- */
export const LESSONS = Object.assign({}, ...Object.values(lessonFiles).map((m) => m.default));
export const lessonFor = (t) => LESSONS[t.id] || (t.alias && LESSONS[t.alias]) || null;
export const hasLesson = (t) => Boolean(lessonFor(t));

/* ---------- pre-generated cards: public/lessons/<courseId>.json (fetched once, then cached) ---------- */
const courseCache = {};
export function loadCourseLessons(courseId) {
  if (!courseCache[courseId]) {
    courseCache[courseId] = fetch('/lessons/' + courseId + '.json')
      .then((r) => (r.ok && (r.headers.get('content-type') || '').includes('json') ? r.json() : {}))
      .catch(() => ({}));
  }
  return courseCache[courseId];
}
// written lesson fields win; generated card fills everything else (how it works, key points, mistakes…)
export async function fullLesson(t) {
  const root = t.alias ? BY_ID[t.alias] : null;
  const [own, viaAlias] = await Promise.all([
    loadCourseLessons(t.course),
    root ? loadCourseLessons(root.course) : Promise.resolve({})
  ]);
  const gen = own[t.id] || (t.alias && viaAlias[t.alias]) || null;
  const written = lessonFor(t);
  if (!gen && !written) return null;
  const merged = { ...(gen || {}) };
  if (written) for (const [k, v] of Object.entries(written)) if (v && (!Array.isArray(v) || v.length)) merged[k] = v;
  return merged;
}

// where else does this term appear (same alias or aliased to it)?
export function relatedPlaces(t) {
  const root = t.alias || t.id;
  return TERMS.filter((x) => x.id !== t.id && (x.id === root || x.alias === root));
}

export const semCourses = (n) => COURSES.filter((c) => c.group === 'sem' && c.sem === n);

/* ---------- search: scores name matches above one-liner matches ---------- */
const norm = (s) => String(s).toLowerCase().replace(/[^a-z0-9+#.\s]/g, ' ');
const INDEX = TERMS.map((t) => ({ t, n: norm(t.name), o: norm(t.one), c: norm(COURSE_MAP[t.course].name) }));

export function searchTerms(q, limit = 40) {
  const words = norm(q).split(/\s+/).filter((w) => w.length > 1 && !STOP.has(w));
  if (!words.length) return [];
  const scored = [];
  for (const row of INDEX) {
    let s = 0;
    for (const w of words) {
      if (row.n === w) s += 12;
      else if (row.n.startsWith(w)) s += 7;
      else if (row.n.includes(w)) s += 5;
      if (row.o.includes(w)) s += 2;
      if (row.c.includes(w)) s += 1;
    }
    if (s) {
      const inName = words.filter((w) => row.n.includes(w)).length;   // reward names matching several words
      if (inName > 1) s += (inName - 1) * 6;
      scored.push([s + (hasLesson(row.t) ? 0.5 : 0), row.t]);
    }
  }
  return scored.sort((a, b) => b[0] - a[0]).slice(0, limit).map((x) => x[1]);
}
const STOP = new Set('what is the a an of in on and or to for how why does do i me my explain with vs difference between about tell give by using use can'.split(' '));

// the same term every day, different each day
export function termOfTheDay() {
  const pool = TERMS.filter(hasLesson);
  const list = pool.length ? pool : TERMS;
  const d = Math.floor(Date.now() / 86400000);
  return list[d % list.length];
}

